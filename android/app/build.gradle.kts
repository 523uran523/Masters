    buildTypes {
        release {
            // Prefer a real signing config from android/key.properties.
            // If it is missing, fall back to debug keys so local/release testing
            // still works. Production uploads must use the release config.
            signingConfig = if (keystorePropertiesFile.exists()) {
                signingConfigs.create("release") {
                    keyAlias = keystoreProperties["keyAlias"] as String?
                    keyPassword = keystoreProperties["keyPassword"] as String?
                    val storeFileName = keystoreProperties["storeFile"] as String?
                    storeFile = if (storeFileName != null) {
                        keystorePropertiesFile.parentFile.resolve(storeFileName)
                    } else {
                        null
                    }
                    storePassword = keystoreProperties["storePassword"] as String?
                }
            } else {
                signingConfigs.getByName("debug")
            }
        }
    }
